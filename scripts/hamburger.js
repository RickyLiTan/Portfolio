function openNav() {
    document.getElementById("MENU").style.padding = "4vw";
    document.getElementById("MENU").style.width = "60vw";
    document.getElementById("MENU").style.paddingTop = "5vw";
    document.getElementById("MENU").style.paddingRight = "5vw";
    document.getElementById("MENU").style.borderLeft = "thin solid #070C25";

  }

function closeNav() {
    document.getElementById("MENU").style.width = "0";
    document.getElementById("MENU").style.padding = "0";
    document.getElementById("MENU").style.border = "0";
}