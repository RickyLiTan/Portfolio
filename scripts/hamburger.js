function openNav() {
    document.getElementById("MENU").style.padding = "4vw";
    document.getElementById("MENU").style.width = "35vw";
    document.getElementById("MENU").style.paddingTop = "2vw";
  }

function closeNav() {
    document.getElementById("MENU").style.width = "0";
    document.getElementById("MENU").style.padding = "0";
    document.getElementById("MENU").style.border = "0";
}